
-- ============================================================
-- V1: Create Asset Management System schema
-- ============================================================

-- 1. Roles
CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

-- 2. Departments
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- 3. Users
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    department_id BIGINT REFERENCES departments(id),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- 4. Asset types
CREATE TABLE asset_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- 5. Locations
CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    city VARCHAR(100),
    country VARCHAR(100),
    floor VARCHAR(50),
    room_location VARCHAR(255)
);

-- 6. Assets
CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code VARCHAR(50) NOT NULL UNIQUE,
    asset_type_id BIGINT NOT NULL REFERENCES asset_types(id),
    name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    actual_found INTEGER CHECK (actual_found >= 0),
    cost_center VARCHAR(50),
    asset_owner_id BIGINT REFERENCES users(id),
    custodian_id BIGINT REFERENCES users(id),
    location_id BIGINT REFERENCES locations(id),
    date_of_checking DATE,
    tagging_status VARCHAR(2)
        CHECK (tagging_status IN ('T', 'NA', 'TR')),
    make_model VARCHAR(255),
    remarks TEXT,

    CONSTRAINT actual_found_not_above_quantity
        CHECK (actual_found IS NULL OR actual_found <= quantity)
);

-- 7. Individual physical asset items
CREATE TABLE asset_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets(id),
    asset_tag VARCHAR(100) UNIQUE,
    serial_number VARCHAR(150),
    serial_number_found VARCHAR(150),

    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN (
            'AVAILABLE',
            'ASSIGNED',
            'UNDER_REPAIR',
            'LOST',
            'DAMAGED',
            'RETIRED',
            'DISPOSED'
        )),

    custodian_id BIGINT REFERENCES users(id),
    location_id BIGINT REFERENCES locations(id),

    -- Physical-item verification
    verification_status VARCHAR(20) NOT NULL DEFAULT 'NOT_CHECKED'
        CHECK (
            verification_status IN (
                'NOT_CHECKED',
                'FOUND',
                'MISSING'
            )
        ),

    -- Tagging is separate from physical-item verification
    tagging_status VARCHAR(2)
        CHECK (tagging_status IS NULL OR tagging_status IN ('T', 'NA', 'TR')),

    date_of_checking DATE,
    gate_pass_number VARCHAR(100)
);

-- ============================================================
-- Indexes
-- ============================================================

CREATE INDEX idx_assets_asset_type
    ON assets(asset_type_id);

CREATE INDEX idx_assets_owner
    ON assets(asset_owner_id);

CREATE INDEX idx_assets_custodian
    ON assets(custodian_id);

CREATE INDEX idx_assets_location
    ON assets(location_id);

CREATE INDEX idx_assets_cost_center
    ON assets(cost_center);

CREATE INDEX idx_asset_items_asset_id
    ON asset_items(asset_id);

CREATE INDEX idx_asset_items_verification_status
    ON asset_items(verification_status);

CREATE INDEX idx_asset_items_tagging_status
    ON asset_items(tagging_status);

CREATE INDEX idx_asset_items_serial_number
    ON asset_items(serial_number);

